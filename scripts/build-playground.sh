#!/usr/bin/env bash
# Rebuild the WebAssembly interpreter and the builtin list used by the static playground.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/adarsh-rs"
rustup target add wasm32-unknown-unknown >/dev/null 2>&1 || true
cargo rustc --release --lib --target wasm32-unknown-unknown --crate-type cdylib
cp target/wasm32-unknown-unknown/release/adarshlang.wasm "$ROOT/playground/adarshlang.wasm"
echo "playground/adarshlang.wasm updated ($(du -h "$ROOT/playground/adarshlang.wasm" | cut -f1))"
# builtin names + docs for highlighting and autocomplete
python3 - "$ROOT" <<'PY'
import json, re, sys
root = sys.argv[1]
src = open(f"{root}/adarsh-rs/src/builtins.rs", encoding="utf-8").read()
items = []
for m in re.finditer(r'b!\("(\w+)",\s*\[([^\]]*)\],\s*\d+,(?:\s*\[[^\]]*\],)?\s*"((?:[^"\\]|\\.)*)"\)', src):
    name, params, doc = m.group(1), m.group(2), m.group(3)
    params = [p.strip().strip('"') for p in params.split(",") if p.strip()]
    items.append([name, params, doc.replace('\\"', '"')])
with open(f"{root}/playground/builtins.js", "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build-playground.sh from adarsh-rs/src/builtins.rs\n")
    f.write("var ADARSH_BUILTINS = " + json.dumps(items, ensure_ascii=False) + ";\n")
print(f"playground/builtins.js updated ({len(items)} builtins)")
PY
